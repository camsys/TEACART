                              vmt_nhs = input$vmt_nhs,
                              ev = input$ev_baseline_input,
                              grid_em = input$grid_emissions_input
                            ),
                            output_format = "pdf_document",
                            output_options = list(
                              keep_tex = TRUE,
                              verbose = TRUE,
                              latex_engine = 'xelatex')
          )
        }
      )
      
    }
